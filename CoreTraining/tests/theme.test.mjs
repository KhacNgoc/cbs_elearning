import { test } from 'node:test';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';

test('theme follows the device, persists overrides and synchronizes browser tabs', async () => {
  const dom = new JSDOM('', { url: 'http://localhost' });
  const listeners = [];
  const media = { matches: true, addEventListener: (_, handler) => listeners.push(handler) };
  dom.window.matchMedia = () => media;
  Object.assign(globalThis, { window: dom.window, document: dom.window.document, localStorage: dom.window.localStorage });
  const { initializeTheme, useTheme, THEME_STORAGE_KEY } = await import('../src/composables/useTheme.ts');
  initializeTheme();
  const theme = useTheme();
  assert.equal(listeners.length, 1, 'initialization must not add duplicate listeners');
  assert.equal(theme.isDark.value, true);
  assert.equal(document.documentElement.dataset.theme, 'dark');
  theme.setTheme('light');
  assert.equal(localStorage.getItem(THEME_STORAGE_KEY), 'light');
  assert.equal(document.documentElement.style.colorScheme, 'light');
  media.matches = true;
  listeners[0]();
  assert.equal(theme.isDark.value, false, 'explicit choice takes precedence over device');
  localStorage.setItem(THEME_STORAGE_KEY, 'dark');
  window.dispatchEvent(new window.StorageEvent('storage', { key: THEME_STORAGE_KEY }));
  assert.equal(theme.isDark.value, true, 'another tab updates the current theme');
  theme.setTheme('system');
  assert.equal(localStorage.getItem(THEME_STORAGE_KEY), null);
  media.matches = false;
  listeners[0]();
  assert.equal(theme.isDark.value, false);
  localStorage.setItem(THEME_STORAGE_KEY, 'invalid');
  window.dispatchEvent(new window.StorageEvent('storage', { key: THEME_STORAGE_KEY }));
  assert.equal(theme.preference.value, 'system');
  Object.defineProperty(globalThis, 'localStorage', { configurable: true, get() { throw new Error('Storage unavailable'); } });
  assert.doesNotThrow(() => theme.setTheme('dark'));
  assert.equal(document.documentElement.dataset.theme, 'dark');
  dom.window.close();
});
