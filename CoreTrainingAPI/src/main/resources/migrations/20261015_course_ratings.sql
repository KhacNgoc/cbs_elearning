-- Optional manual migration for deployments without Hibernate ddl-auto=update.
-- Existing comments.rating remains historical lesson data and is not migrated.
CREATE TABLE IF NOT EXISTS course_ratings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version BIGINT NOT NULL DEFAULT 0,
 user_id BIGINT NOT NULL REFERENCES users(id),
 course_id VARCHAR(255) NOT NULL REFERENCES courses(id),
 stars INTEGER NOT NULL CHECK (stars BETWEEN 1 AND 5),
 content VARCHAR(2000) NOT NULL DEFAULT '',
 created_at TIMESTAMP NOT NULL,
 updated_at TIMESTAMP NOT NULL,
 CONSTRAINT uk_course_rating_user_course UNIQUE(user_id,course_id)
);
CREATE INDEX IF NOT EXISTS ix_course_ratings_course_updated ON course_ratings(course_id,updated_at DESC);
