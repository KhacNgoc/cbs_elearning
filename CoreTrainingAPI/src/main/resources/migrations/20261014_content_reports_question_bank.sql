-- PostgreSQL. Run once before starting the upgraded application.
-- Hibernate update adds tables/columns, but does not reliably update old enum CHECK constraints.
BEGIN;
ALTER TABLE questions ADD COLUMN IF NOT EXISTS explanation text;
ALTER TABLE questions ADD COLUMN IF NOT EXISTS bank_question_id bigint;
ALTER TABLE questions ADD COLUMN IF NOT EXISTS bank_question_code varchar(255);

CREATE TABLE IF NOT EXISTS bank_questions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint,
    code varchar(80) NOT NULL UNIQUE,
    course_id varchar(255) NOT NULL REFERENCES courses(id),
    related_lesson_id varchar(255) REFERENCES lessons(id),
    text text NOT NULL,
    type varchar(255) NOT NULL CHECK (type IN ('SINGLE_CHOICE','MULTIPLE_CHOICE')),
    explanation text,
    difficulty varchar(255) NOT NULL CHECK (difficulty IN ('EASY','MEDIUM','HARD')),
    status varchar(255) NOT NULL CHECK (status IN ('DRAFT','ACTIVE','ARCHIVED')),
    updated_at timestamp(6)
);
CREATE TABLE IF NOT EXISTS bank_question_options (
    question_id bigint NOT NULL REFERENCES bank_questions(id),
    option_order integer NOT NULL,
    option_text text,
    PRIMARY KEY(question_id,option_order)
);
CREATE TABLE IF NOT EXISTS bank_question_answers (
    question_id bigint NOT NULL REFERENCES bank_questions(id),
    answer_order integer NOT NULL,
    answer_index integer,
    PRIMARY KEY(question_id,answer_order)
);
CREATE TABLE IF NOT EXISTS lesson_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint,
    lesson_id varchar(255) NOT NULL REFERENCES lessons(id),
    reporter_id bigint NOT NULL REFERENCES users(id),
    content text NOT NULL,
    status varchar(255) NOT NULL CHECK (status IN ('NEW','IN_REVIEW','RESOLVED','DISMISSED')),
    resolution text,
    reviewer_id bigint REFERENCES users(id),
    created_at timestamp(6),
    reviewed_at timestamp(6)
);
CREATE TABLE IF NOT EXISTS lesson_report_images (
    report_id bigint NOT NULL REFERENCES lesson_reports(id),
    image_order integer NOT NULL,
    image_name varchar(255),
    PRIMARY KEY(report_id,image_order)
);
CREATE INDEX IF NOT EXISTS idx_bank_questions_course ON bank_questions(course_id);
CREATE INDEX IF NOT EXISTS idx_lesson_reports_lesson ON lesson_reports(lesson_id);
CREATE INDEX IF NOT EXISTS idx_lesson_reports_created ON lesson_reports(created_at);
ALTER TABLE notifications DROP CONSTRAINT IF EXISTS notifications_type_check;
ALTER TABLE notifications ADD CONSTRAINT notifications_type_check CHECK (type IN (
    'COMMENT_REPLY','ENROLLMENT_REQUEST','ENROLLMENT_APPROVED','ENROLLMENT_REJECTED','LESSON_REPORT'
));
COMMIT;
