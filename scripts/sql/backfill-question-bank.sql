BEGIN;
SET LOCAL lock_timeout = '10s';

-- 1. Bổ sung cấu trúc nếu chưa có. Cơ sở dữ liệu đã nâng cấp có thể chạy lại.
ALTER TABLE questions ADD COLUMN IF NOT EXISTS explanation text;
ALTER TABLE questions ADD COLUMN IF NOT EXISTS bank_question_id bigint;
ALTER TABLE questions ADD COLUMN IF NOT EXISTS bank_question_code varchar(255);

CREATE TABLE IF NOT EXISTS question_correct_answers (
    question_id bigint NOT NULL REFERENCES questions(id),
    answer_order integer NOT NULL,
    answer_index integer NOT NULL,
    PRIMARY KEY (question_id, answer_order)
);

CREATE TABLE IF NOT EXISTS bank_questions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint,
    code varchar(80) NOT NULL UNIQUE,
    course_id varchar(255) NOT NULL REFERENCES courses(id),
    related_lesson_id varchar(255) REFERENCES lessons(id),
    text text NOT NULL,
    type varchar(255) NOT NULL CHECK (type IN ('SINGLE_CHOICE', 'MULTIPLE_CHOICE')),
    explanation text,
    difficulty varchar(255) NOT NULL CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    status varchar(255) NOT NULL CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED')),
    updated_at timestamp(6)
);
CREATE TABLE IF NOT EXISTS bank_question_options (
    question_id bigint NOT NULL REFERENCES bank_questions(id),
    option_order integer NOT NULL,
    option_text text,
    PRIMARY KEY (question_id, option_order)
);
CREATE TABLE IF NOT EXISTS bank_question_answers (
    question_id bigint NOT NULL REFERENCES bank_questions(id),
    answer_order integer NOT NULL,
    answer_index integer,
    PRIMARY KEY (question_id, answer_order)
);
CREATE INDEX IF NOT EXISTS idx_bank_questions_course ON bank_questions(course_id);

-- 2. Kiểm tra dữ liệu nguồn, sao chép và gắn liên kết trong cùng transaction.
-- Tránh thay đổi dữ liệu nguồn/ngân hàng trong lúc sao chép và gắn liên kết.
LOCK TABLE questions, bank_questions, question_options, question_correct_answers,
    bank_question_options, bank_question_answers, quizzes, lessons
    IN SHARE ROW EXCLUSIVE MODE;

DO $$
DECLARE dangling_ids text;
BEGIN
    SELECT string_agg(q.id::text, ', ' ORDER BY q.id) INTO dangling_ids
    FROM questions q
    LEFT JOIN bank_questions b ON b.id = q.bank_question_id
    WHERE q.bank_question_id IS NOT NULL AND b.id IS NULL;
    IF dangling_ids IS NOT NULL THEN
        RAISE EXCEPTION 'Câu hỏi có bank_question_id không tồn tại: %. Cần sửa liên kết trước khi chuyển dữ liệu.', dangling_ids;
    END IF;
END $$;

CREATE TEMP TABLE tmp_question_bank_backfill ON COMMIT DROP AS
WITH source AS (
    SELECT q.id AS source_id, q.course_id, q.lesson_id AS source_lesson_id,
           q.quiz_id, z.id AS existing_quiz_id, z.lesson_id AS quiz_lesson_id,
           COALESCE(q.lesson_id, z.lesson_id) AS related_lesson_id,
           l.course_id AS lesson_course_id,
           q.text, q.explanation, q.question_type,
           ARRAY(SELECT o.option_text FROM question_options o
                 WHERE o.question_id = q.id ORDER BY o.option_order) AS option_values,
           ARRAY(SELECT o.option_order FROM question_options o
                 WHERE o.question_id = q.id ORDER BY o.option_order) AS option_positions,
           CASE WHEN EXISTS (SELECT 1 FROM question_correct_answers a WHERE a.question_id = q.id)
                THEN ARRAY(SELECT DISTINCT a.answer_index FROM question_correct_answers a
                           WHERE a.question_id = q.id ORDER BY a.answer_index)
                ELSE ARRAY[q.correct_answer] END AS answer_values
    FROM questions q
    LEFT JOIN quizzes z ON z.id = q.quiz_id
    LEFT JOIN lessons l ON l.id = COALESCE(q.lesson_id, z.lesson_id)
    WHERE q.bank_question_id IS NULL
)
SELECT source.*,
       'MIG-Q-' || source_id::text AS bank_code,
       COALESCE(NULLIF(question_type, ''),
           CASE WHEN cardinality(answer_values) > 1 THEN 'MULTIPLE_CHOICE' ELSE 'SINGLE_CHOICE' END) AS bank_type
FROM source;

-- Dừng trước khi ghi nếu dữ liệu cũ không đạt các quy tắc của ngân hàng.
DO $$
DECLARE invalid_rows text; conflicting_codes text;
BEGIN
    SELECT string_agg(source_id::text || ': ' || reason, E'\n' ORDER BY source_id)
    INTO invalid_rows
    FROM (
        SELECT source_id,
            CASE
                WHEN existing_quiz_id IS NULL OR related_lesson_id IS NULL OR lesson_course_id IS NULL
                    THEN 'Không xác định được bài kiểm tra/bài học nguồn'
                WHEN course_id IS DISTINCT FROM lesson_course_id
                    OR (source_lesson_id IS NOT NULL AND source_lesson_id IS DISTINCT FROM quiz_lesson_id)
                    THEN 'Khóa học, bài học và bài kiểm tra không khớp'
                WHEN text IS NULL OR btrim(text) = '' OR length(text) > 20000
                    THEN 'Nội dung rỗng hoặc vượt 20.000 ký tự'
                WHEN length(explanation) > 20000 THEN 'Giải thích vượt 20.000 ký tự'
                WHEN cardinality(option_values) NOT BETWEEN 3 AND 6
                    THEN 'Cần từ 3 đến 6 lựa chọn'
                WHEN EXISTS (SELECT 1 FROM unnest(option_values) AS x(value)
                             WHERE value IS NULL OR btrim(value) = '' OR length(value) > 5000)
                    THEN 'Lựa chọn rỗng hoặc vượt 5.000 ký tự'
                WHEN (SELECT count(DISTINCT lower(btrim(value))) FROM unnest(option_values) AS x(value))
                     <> cardinality(option_values) THEN 'Các lựa chọn trùng nhau'
                WHEN option_positions IS DISTINCT FROM ARRAY(SELECT generate_series(0, cardinality(option_values) - 1))
                    THEN 'Thứ tự lựa chọn phải liên tục từ 0'
                WHEN cardinality(answer_values) = 0
                    OR EXISTS (SELECT 1 FROM unnest(answer_values) AS x(value)
                               WHERE value IS NULL OR value < 0 OR value >= cardinality(option_values))
                    THEN 'Chỉ số đáp án đúng không hợp lệ'
                WHEN bank_type NOT IN ('SINGLE_CHOICE', 'MULTIPLE_CHOICE') THEN 'Loại câu hỏi không hỗ trợ'
                WHEN bank_type = 'SINGLE_CHOICE' AND cardinality(answer_values) <> 1
                    THEN 'Câu một lựa chọn cần đúng một đáp án'
                WHEN bank_type = 'MULTIPLE_CHOICE'
                     AND (cardinality(answer_values) < 2 OR cardinality(answer_values) >= cardinality(option_values))
                    THEN 'Câu nhiều lựa chọn cần ít nhất hai đáp án đúng, không chọn tất cả'
            END AS reason
        FROM tmp_question_bank_backfill
    ) checked
    WHERE reason IS NOT NULL;
    IF invalid_rows IS NOT NULL THEN
        RAISE EXCEPTION E'Không chuyển dữ liệu vì có câu hỏi không hợp lệ:\n%', invalid_rows;
    END IF;

    SELECT string_agg(c.bank_code, ', ' ORDER BY c.source_id) INTO conflicting_codes
    FROM tmp_question_bank_backfill c
    JOIN bank_questions b ON upper(b.code) = c.bank_code;
    IF conflicting_codes IS NOT NULL THEN
        RAISE EXCEPTION 'Mã ngân hàng đã tồn tại nhưng câu nguồn chưa có liên kết: %. Không tự ghi đè hoặc đoán liên kết.', conflicting_codes;
    END IF;
END $$;

CREATE TEMP TABLE tmp_question_bank_backfill_map ON COMMIT DROP AS
WITH inserted AS (
    INSERT INTO bank_questions
        (version, code, course_id, related_lesson_id, text, type, explanation, difficulty, status, updated_at)
    SELECT 0, bank_code, course_id, related_lesson_id, text, bank_type, explanation,
           'MEDIUM', 'ACTIVE', localtimestamp
    FROM tmp_question_bank_backfill
    ORDER BY source_id
    RETURNING id, code
)
SELECT c.source_id, inserted.id AS bank_id, inserted.code AS bank_code
FROM inserted
JOIN tmp_question_bank_backfill c ON c.bank_code = inserted.code;

INSERT INTO bank_question_options (question_id, option_order, option_text)
SELECT m.bank_id, (x.position - 1)::integer, x.value
FROM tmp_question_bank_backfill c
JOIN tmp_question_bank_backfill_map m ON m.source_id = c.source_id
CROSS JOIN LATERAL unnest(c.option_values) WITH ORDINALITY AS x(value, position);

INSERT INTO bank_question_answers (question_id, answer_order, answer_index)
SELECT m.bank_id, (x.position - 1)::integer, x.value
FROM tmp_question_bank_backfill c
JOIN tmp_question_bank_backfill_map m ON m.source_id = c.source_id
CROSS JOIN LATERAL unnest(c.answer_values) WITH ORDINALITY AS x(value, position);

UPDATE questions q
SET bank_question_id = m.bank_id, bank_question_code = m.bank_code
FROM tmp_question_bank_backfill_map m
WHERE q.id = m.source_id;

SELECT (SELECT count(*) FROM questions) AS tong_cau_hoi_trong_bai_kiem_tra,
       (SELECT count(*) FROM tmp_question_bank_backfill_map) AS so_cau_vua_them_vao_ngan_hang,
       (SELECT count(*) FROM questions) - (SELECT count(*) FROM tmp_question_bank_backfill_map)
           AS so_cau_da_co_lien_ket_duoc_giu_nguyen;

COMMIT;
